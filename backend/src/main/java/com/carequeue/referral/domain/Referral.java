package com.carequeue.referral.domain;

import com.carequeue.clinic.domain.Clinic;
import com.carequeue.patient.domain.Patient;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.envers.Audited;
import org.hibernate.envers.NotAudited;
import org.hibernate.envers.RelationTargetAuditMode;
import org.hibernate.type.SqlTypes;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.Objects;

@Entity
@Table(name = "referral")
@Audited
public class Referral {

	@Id
	@GeneratedValue(strategy = GenerationType.IDENTITY)
	private Long id;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "patient_id")
	@Audited(targetAuditMode = RelationTargetAuditMode.NOT_AUDITED)
	private Patient patient;

	@ManyToOne(fetch = FetchType.LAZY, optional = false)
	@JoinColumn(name = "clinic_id")
	@Audited(targetAuditMode = RelationTargetAuditMode.NOT_AUDITED)
	private Clinic clinic;

	@Column(name = "referring_gp", nullable = false, length = 120)
	private String referringGp;

	@Column(name = "external_ref", unique = true, length = 64)
	private String externalRef;

	@Enumerated(EnumType.STRING)
	@Column(nullable = false)
	private ReferralSource source;

	// Immutable after import and holds PII, so it is not audited (a copy per revision would duplicate PII).
	@NotAudited
	@Column(name = "clinical_notes", nullable = false)
	private String clinicalNotes;

	@NotAudited
	@JdbcTypeCode(SqlTypes.JSON)
	@Column(name = "raw_message", columnDefinition = "jsonb")
	private String rawMessage;

	@Enumerated(EnumType.STRING)
	@Column(nullable = false)
	private ReferralStatus status;

	@Column(name = "ai_summary")
	private String aiSummary;

	@Enumerated(EnumType.STRING)
	@Column(name = "suggested_priority")
	private Priority suggestedPriority;

	@Enumerated(EnumType.STRING)
	@Column(name = "suggestion_source")
	private SuggestionSource suggestionSource;

	@Column(name = "suggestion_confidence", precision = 3, scale = 2)
	private BigDecimal suggestionConfidence;

	@Column(name = "prompt_version", length = 20)
	private String promptVersion;

	@JdbcTypeCode(SqlTypes.JSON)
	@Column(name = "red_flags", columnDefinition = "jsonb")
	private List<String> redFlags;

	@Enumerated(EnumType.STRING)
	@Column(name = "confirmed_priority")
	private Priority confirmedPriority;

	// Read-only: generated by Postgres from confirmed_priority and read by the waiting-list
	// ORDER BY. Stale in memory after confirmPriority — the value is refreshed on reload.
	@NotAudited
	@Column(name = "priority_rank", insertable = false, updatable = false)
	private Short priorityRank;

	@Column(name = "triage_note")
	private String triageNote;

	@Column(name = "triaged_by", length = 60)
	private String triagedBy;

	@Column(name = "triaged_at")
	private Instant triagedAt;

	@Column(name = "received_at", nullable = false)
	private Instant receivedAt;

	@Version
	private long version;

	protected Referral() {
	}

	private Referral(Patient patient, Clinic clinic, String referringGp, String externalRef,
			ReferralSource source, String clinicalNotes, String rawMessage, Instant receivedAt) {
		this.patient = Objects.requireNonNull(patient, "patient is required");
		this.clinic = Objects.requireNonNull(clinic, "clinic is required");
		this.referringGp = Objects.requireNonNull(referringGp, "referringGp is required");
		this.externalRef = externalRef;
		this.source = Objects.requireNonNull(source, "source is required");
		this.clinicalNotes = Objects.requireNonNull(clinicalNotes, "clinicalNotes is required");
		this.rawMessage = rawMessage;
		this.receivedAt = Objects.requireNonNull(receivedAt, "receivedAt is required");
		this.status = ReferralStatus.RECEIVED;
	}

	public static Referral receive(Patient patient, Clinic clinic, String referringGp, String externalRef,
			ReferralSource source, String clinicalNotes, String rawMessage, Instant receivedAt) {
		return new Referral(patient, clinic, referringGp, externalRef, source, clinicalNotes, rawMessage, receivedAt);
	}

	public void recordSuggestion(String summary, Priority suggested, List<String> redFlags,
			BigDecimal confidence, String promptVersion, SuggestionSource source) {
		Objects.requireNonNull(suggested, "suggested priority is required");
		Objects.requireNonNull(source, "suggestion source is required");
		if (confidence != null
				&& (confidence.compareTo(BigDecimal.ZERO) < 0 || confidence.compareTo(BigDecimal.ONE) > 0)) {
			throw new IllegalArgumentException("confidence must be between 0 and 1");
		}
		moveTo(ReferralStatus.AI_SUGGESTED);
		this.aiSummary = summary;
		this.suggestedPriority = suggested;
		this.redFlags = redFlags == null ? List.of() : List.copyOf(redFlags);
		this.suggestionConfidence = confidence;
		this.promptVersion = promptVersion;
		this.suggestionSource = source;
	}

	public void confirmPriority(Priority priority, String note, String clinician, Instant at) {
		Objects.requireNonNull(priority, "priority is required");
		Objects.requireNonNull(clinician, "clinician is required");
		Objects.requireNonNull(at, "triaged-at is required");
		moveTo(ReferralStatus.TRIAGED);
		this.confirmedPriority = priority;
		this.triageNote = note;
		this.triagedBy = clinician;
		this.triagedAt = at;
	}

	public void markBooked() {
		moveTo(ReferralStatus.BOOKED);
	}

	public void reject() {
		moveTo(ReferralStatus.REJECTED);
	}

	private void moveTo(ReferralStatus next) {
		if (!status.canMoveTo(next)) {
			throw new InvalidStatusTransitionException(status, next);
		}
		status = next;
	}

	public Long getId() {
		return id;
	}

	public Patient getPatient() {
		return patient;
	}

	public Clinic getClinic() {
		return clinic;
	}

	public String getReferringGp() {
		return referringGp;
	}

	public String getExternalRef() {
		return externalRef;
	}

	public ReferralSource getSource() {
		return source;
	}

	public String getClinicalNotes() {
		return clinicalNotes;
	}

	public String getRawMessage() {
		return rawMessage;
	}

	public ReferralStatus getStatus() {
		return status;
	}

	public String getAiSummary() {
		return aiSummary;
	}

	public Priority getSuggestedPriority() {
		return suggestedPriority;
	}

	public SuggestionSource getSuggestionSource() {
		return suggestionSource;
	}

	public BigDecimal getSuggestionConfidence() {
		return suggestionConfidence;
	}

	public String getPromptVersion() {
		return promptVersion;
	}

	public List<String> getRedFlags() {
		return redFlags;
	}

	public Priority getConfirmedPriority() {
		return confirmedPriority;
	}

	public Short getPriorityRank() {
		return priorityRank;
	}

	public String getTriageNote() {
		return triageNote;
	}

	public String getTriagedBy() {
		return triagedBy;
	}

	public Instant getTriagedAt() {
		return triagedAt;
	}

	public Instant getReceivedAt() {
		return receivedAt;
	}

	public long getVersion() {
		return version;
	}
}
